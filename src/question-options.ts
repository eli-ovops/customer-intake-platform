type Answers = Record<string, string | string[]>;
export type Choice = { value: string; text: string };
export type RoutingQuestion = {
  name: string;
  title: string;
  type: "dropdown" | "checkbox";
  choices: Choice[];
  when: (a: Answers) => boolean;
  description: string;
};
export const choices = (values: string[]): Choice[] =>
  values.map((value, i) => ({
    value,
    text: `${String.fromCharCode(65 + i)}. ${value}`,
  }));
const selected = (field: string, values: string[]) => (a: Answers) =>
  a.mode === "detailed" && values.includes(String(a[field] ?? ""));
export const pick = (
  name: string,
  title: string,
  values: string[],
  when: RoutingQuestion["when"],
  multiple = false,
): RoutingQuestion => ({
  name,
  title,
  type: multiple ? "checkbox" : "dropdown",
  choices: choices(values),
  when,
  description: multiple
    ? "可多选；不确定可以跳过，访谈时再确认。"
    : "选最接近的一项；不确定可以跳过，访谈时再确认。",
});
